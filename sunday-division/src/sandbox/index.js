'use strict';
const path = require('node:path');
const { fork } = require('node:child_process');
const { RetryableError, FatalError } = require('../orchestrator/errors');

const SCRIPT = path.join(__dirname, 'inspect-file.js');

/**
 * Inspect an untrusted stored file in an isolated child process:
 *  - Node permission model: read access to the inspector script and that one file only;
 *    no writes, no child processes, no worker threads, no native add-ons
 *  - empty environment, so no API keys or other credentials are present
 *  - memory cap and wall-clock timeout
 * The path is generated by the application (random storage name), never taken from input,
 * and is passed as an argument vector — no shell is involved.
 */
function createSandbox({ timeoutMs = 15000 } = {}) {
  return {
    inspect(filePath) {
      return new Promise((resolve, reject) => {
        const child = fork(SCRIPT, [filePath], {
          env: {},
          execArgv: ['--permission', `--allow-fs-read=${SCRIPT}`, `--allow-fs-read=${filePath}`, '--max-old-space-size=128'],
          stdio: ['ignore', 'ignore', 'pipe', 'ipc'],
          serialization: 'json',
        });
        let settled = false;
        const finish = (fn, v) => { if (!settled) { settled = true; clearTimeout(timer); fn(v); } };
        const timer = setTimeout(() => { child.kill('SIGKILL'); finish(reject, new RetryableError('File inspection timed out.')); }, timeoutMs);
        child.on('message', (m) => {
          if (m && m.ok) finish(resolve, { ...m.report, isolated: true });
          else finish(reject, new FatalError(`File could not be inspected: ${m && m.error}`));
        });
        child.on('error', (err) => finish(reject, new RetryableError(`Inspector failed to start: ${err.message}`)));
        child.on('exit', (code) => finish(reject, new RetryableError(`Inspector exited (${code}) without a result.`)));
      });
    },
  };
}

module.exports = { createSandbox, SCRIPT };
